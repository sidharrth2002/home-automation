"""Copy what the TV app shares with the Hub out of frontend/hub/app.js, so there's one source for both:
the icon set (-> ui/HubIcons.kt) and the screensaver's quotes (-> ui/Quotes.kt). Rerun after changing either there:
    python3 tv-app/hub_sync.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "frontend" / "hub" / "app.js").read_text()
CLOUD = re.search(r'const CLOUD = `(.*?)`', src).group(1)
icons = {}
for name, arg in re.findall(r"^  (\w+): svg\((.*)\),?\s*$", src, re.M):  # svg(`...` + CLOUD + `...`, extra?)
    arg = arg.split("`, ")[0] + ("`" if "`, " in arg else "")  # drop svg()'s second argument
    icons[name] = "".join(CLOUD if part.strip() == "CLOUD" else part.strip().strip("`").replace("${CLOUD}", CLOUD)
                          for part in arg.split(" + "))


def num(a, k, d=0.0):
    m = re.search(rf'\b{k}="([-\d.]+)"', a)
    return float(m.group(1)) if m else d


def to_paths(body: str) -> list[str]:
    """Every shape as an SVG path string (circle, ellipse, rect, line and polyline become paths)."""
    out = []
    for tag, a in re.findall(r"<(\w+)([^>]*)/?>", body):
        if tag == "path":
            out.append(re.search(r'\bd="([^"]+)"', a).group(1))
        elif tag in ("circle", "ellipse"):
            cx, cy = num(a, "cx"), num(a, "cy")
            rx = num(a, "r") if tag == "circle" else num(a, "rx")
            ry = num(a, "r") if tag == "circle" else num(a, "ry")
            out.append(f"M{cx - rx} {cy}a{rx} {ry} 0 1 0 {2 * rx} 0a{rx} {ry} 0 1 0 {-2 * rx} 0")
        elif tag == "rect":
            x, y, w, h, r = num(a, "x"), num(a, "y"), num(a, "width"), num(a, "height"), num(a, "rx")
            if r:
                out.append(f"M{x + r} {y}h{w - 2 * r}a{r} {r} 0 0 1 {r} {r}v{h - 2 * r}a{r} {r} 0 0 1 {-r} {r}"
                           f"h{-(w - 2 * r)}a{r} {r} 0 0 1 {-r} {-r}v{-(h - 2 * r)}a{r} {r} 0 0 1 {r} {-r}z")
            else:
                out.append(f"M{x} {y}h{w}v{h}h{-w}z")
        elif tag == "line":
            out.append(f"M{num(a, 'x1')} {num(a, 'y1')}L{num(a, 'x2')} {num(a, 'y2')}")
        elif tag in ("polyline", "polygon"):
            pts = re.search(r'points="([^"]+)"', a).group(1).split()
            out.append("M" + "L".join(pts) + ("z" if tag == "polygon" else ""))
    return out


lines = ["// Generated by tv-app/hub_sync.py from the Hub's icon set (frontend/hub/app.js). Don't edit by hand.",
         "package com.sid.home.ui", "", "object HubIcons {"]
for name, body in icons.items():
    paths = ", ".join(f'"{p}"' for p in to_paths(body))
    lines.append(f"    val {name} = hubIcon({paths})")
lines.append("}")
out = ROOT / "tv-app" / "app" / "src" / "main" / "java" / "com" / "sid" / "home" / "ui" / "HubIcons.kt"
out.write_text("\n".join(lines) + "\n")
print(f"{len(icons)} icons -> {out.relative_to(ROOT)}")

# the screensaver's quotes
block = re.search(r"^const QUOTES = \[(.*?)^\];", src, re.M | re.S).group(1)
quotes = re.findall(r'\["((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\]', block)
kt = ["// Generated by tv-app/hub_sync.py from the Hub's QUOTES (frontend/hub/app.js). Don't edit by hand.",
      "package com.sid.home.ui", "", "val QUOTES = listOf("]
def kstr(t):
    return '"' + t.replace("$", "\\$") + '"'
kt += [f"    {kstr(q)} to {kstr(a)}," for q, a in quotes]
kt.append(")")
(out.parent / "Quotes.kt").write_text("\n".join(kt) + "\n")
print(f"{len(quotes)} quotes -> {(out.parent / 'Quotes.kt').relative_to(ROOT)}")
